using Backend.Controllers;
using Backend.Models;

namespace Backend.Tests;

[TestClass]
public sealed class ReportsControllerTest : SqlControllerTest
{
    [TestMethod]
    public async Task MoviePerformanceReportShouldReturnAggregatedRows()
    {
        // Use the screening date, not the booking date, to aggregate a known sale.
        var (showtime, _) = await CreateBookedShowtimeAsync();
        var date = DateOnly.FromDateTime(showtime.StartDateTime);
        var rows = Rows<MoviePerformanceResult>(await new ReportsController(Configuration).MoviePerformance(date, date));
        var movie = rows.Single(row => row.MovieId == showtime.MovieId);
        Assert.AreEqual(1, movie.ShowtimeCount);
        Assert.AreEqual(3L, movie.TicketsSold);
        Assert.AreEqual(3 * showtime.TicketPrice, movie.TotalRevenue);
        Assert.AreEqual(3m, movie.AverageTicketsPerShowtime);
    }

    [TestMethod]
    public async Task CustomerBookingActivityReportShouldReturnRankedRows()
    {
        // Read the booking date generated by SQL Server rather than assuming its time zone.
        var (showtime, booking) = await CreateBookedShowtimeAsync();
        var date = DateOnly.FromDateTime(booking.BookingDate);
        var rows = Rows<CustomerBookingActivityResult>(
            await new ReportsController(Configuration).CustomerBookingActivity(date, date));
        var customer = rows.Single(row => row.CustomerId == booking.CustomerId);
        Assert.AreEqual("Test Customer", customer.CustomerName);
        Assert.AreEqual(1, customer.BookingCount);
        Assert.AreEqual(3L, customer.TicketsPurchased);
        Assert.AreEqual(3 * showtime.TicketPrice, customer.TotalSpent);

        // RANK uses the number of rows ahead of this spend, including ties ahead of it.
        var ordered = rows.OrderByDescending(row => row.TotalSpent).ThenBy(row => row.CustomerId).ToList();
        CollectionAssert.AreEqual(ordered.Select(row => row.CustomerId).ToArray(), rows.Select(row => row.CustomerId).ToArray());
        Assert.AreEqual(1L + rows.Count(row => row.TotalSpent > customer.TotalSpent), customer.SpendingRank);
    }

    [TestMethod]
    public async Task ScreenRoomUtilizationReportShouldReturnOccupancyRates()
    {
        // Three tickets in the fixture's 20-seat room give exactly 15 percent occupancy.
        var (showtime, _) = await CreateBookedShowtimeAsync();
        var date = DateOnly.FromDateTime(showtime.StartDateTime);
        var rows = Rows<ScreenRoomUtilizationResult>(
            await new ReportsController(Configuration).ScreenRoomUtilization(date, date));
        var room = rows.Single(row => row.ScreenRoomId == showtime.ScreenRoomId);
        Assert.AreEqual(1, room.ShowtimeCount);
        Assert.AreEqual(3L, room.TicketsBooked);
        Assert.AreEqual(20L, room.SeatsOffered);
        Assert.AreEqual(15m, room.OccupancyRate);
    }

    [TestMethod]
    public async Task MovieReviewSummaryReportShouldFilterByMinimumReviewCount()
    {
        // Give a new movie one review so it meets a threshold of one but not two.
        var movieId = CreatedId(await new MoviesController(Configuration).Create(NewMovie()), "movieId");
        var customerId = CreatedId(await new CustomersController(Configuration).Create(NewCustomer()), "customerId");
        CreatedId(await new ReviewsController(Configuration).Create(new ReviewRequest
        {
            MovieId = movieId,
            CustomerId = customerId,
            Rating = 4
        }), "reviewId");

        // Verify the mapped aggregate fields, then confirm HAVING removes the row.
        var reports = new ReportsController(Configuration);
        var movie = Rows<MovieReviewSummaryResult>(await reports.MovieReviewSummary(1)).Single(row => row.MovieId == movieId);
        Assert.AreEqual(1, movie.ReviewCount);
        Assert.AreEqual(4m, movie.AverageRating);
        Assert.AreEqual((byte)4, movie.HighestRating);
        Assert.AreEqual((byte)4, movie.LowestRating);
        Assert.IsFalse(Rows<MovieReviewSummaryResult>(await reports.MovieReviewSummary(2)).Any(row => row.MovieId == movieId));
    }

    private async Task<(ShowtimeRequest Showtime, Booking Booking)> CreateBookedShowtimeAsync()
    {
        // Run the normal write actions to give the report known rows inside the test transaction.
        var request = await NewShowtimeAsync();
        var showtimeId = CreatedId(await new ShowtimesController(Configuration).Create(request), "showtimeId");
        var customerId = CreatedId(await new CustomersController(Configuration).Create(NewCustomer()), "customerId");
        var bookings = new BookingsController(Configuration);
        CreatedId(await bookings.Create(new BookingRequest
        {
            CustomerId = customerId,
            ShowtimeId = showtimeId,
            NumberOfTickets = 3
        }), "bookingId");
        return (request, Rows<Booking>(await bookings.Get(customerId)).Single());
    }
}
